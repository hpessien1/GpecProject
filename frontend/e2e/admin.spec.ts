import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'
import { ADMIN, BREACHED_PASSWORD, CONTACT_REF, ENQUIRY_REF, UPLOADED_IMAGE, logInAsAdmin, mockApi } from './support/sampleApi'

test.describe('admin login', () => {
  test('a wrong password shows a focused message; the right one opens the panel', async ({ page }) => {
    await mockApi(page)
    await page.goto('/#admin')
    await expect(page).toHaveTitle('Admin | GPEC')
    await page.getByLabel('Email address').fill(ADMIN.email)
    await page.getByLabel('Password', { exact: true }).fill('not the password')
    await page.getByRole('button', { name: 'Log in' }).click()
    await expect(page.locator('.form-error')).toHaveText('Email or password is incorrect.')
    await expect(page.locator('.form-error')).toBeFocused()
    await page.getByLabel('Password', { exact: true }).fill(ADMIN.password)
    await page.getByRole('button', { name: 'Log in' }).click()
    await expect(page.getByRole('heading', { name: 'Products' })).toBeVisible()
  })

  test('the password can be shown and hidden, and is hidden again when the form is sent', async ({ page }) => {
    await mockApi(page)
    await page.goto('/#admin')
    const password = page.getByLabel('Password', { exact: true })
    await password.fill('not the password')
    await expect(password).toHaveAttribute('type', 'password')
    await page.getByRole('button', { name: 'Show password' }).click()
    await expect(password).toHaveAttribute('type', 'text')
    await expect(password).toHaveAttribute('spellcheck', 'false')
    await expect(page.getByRole('button', { name: 'Hide password' })).toHaveText('Hide')
    await page.getByRole('button', { name: 'Hide password' }).click()
    await expect(password).toHaveAttribute('type', 'password')
    await page.getByRole('button', { name: 'Show password' }).click()
    await page.getByLabel('Email address').fill(ADMIN.email)
    await page.getByRole('button', { name: 'Log in' }).click()
    await expect(page.locator('.form-error')).toHaveText('Email or password is incorrect.')
    await expect(password).toHaveAttribute('type', 'password')
    await expect(password).toHaveValue('not the password')
  })

  test('each password on the change-password form has its own toggle', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    await page.goto('/#admin/password')
    await expect(page.getByRole('button', { name: 'Show password' })).toHaveCount(3)
    await page.getByRole('button', { name: 'Show password' }).nth(1).click()
    await expect(page.getByLabel('New password', { exact: true })).toHaveAttribute('type', 'text')
    await expect(page.getByLabel('Current password')).toHaveAttribute('type', 'password')
    await expect(page.getByLabel('New password again')).toHaveAttribute('type', 'password')
  })

  test('returns to the login screen with a notice when the session ends', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    api.loggedIn = false
    await page.getByRole('link', { name: 'Order enquiries' }).click()
    await expect(page.getByText('Your session has ended. Please log in again.')).toBeVisible()
  })

  test('logs out', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('button', { name: 'Log out' }).click()
    await expect(page.getByText('You have logged out.')).toBeVisible()
    expect(api.requests.some((r) => r.method === 'DELETE' && r.path === '/api/admin/session')).toBe(true)
  })
})

test.describe('products and prices', () => {
  test('lists products with formatted prices and status tags', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    const first = page.locator('.admin-product-list li').first()
    await expect(first).toContainText('Custom control panel')
    await expect(first).toContainText('₦1,500.50')
    await expect(page.locator('.admin-product-list li').nth(1)).toContainText('Archived')
  })

  test('saves only the changed field and records it in the history', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('link', { name: 'Edit Custom control panel' }).click()
    await page.getByLabel('Price').fill('2,750')
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page.locator('.success-message')).toHaveText('Changes saved.')
    expect(api.requests.find((r) => r.method === 'PATCH')?.body).toEqual({ price: 275000 })
    await expect(page.locator('.admin-history li').first()).toContainText('Price: ₦1,500.50 → ₦2,750.00')
  })

  test('rejects a badly typed price before sending anything', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('link', { name: 'Edit Custom control panel' }).click()
    await page.getByLabel('Price').fill('12.345')
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page.locator('#product-price-error')).toContainText('Enter an amount such as 1500 or 1500.50')
    expect(api.requests.some((r) => r.method === 'PATCH')).toBe(false)
  })

  test('uploads a photo from the device, previews it, and saves it to the product', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('link', { name: 'Edit Custom control panel' }).click()
    const preview = page.locator('.admin-image-preview')
    await expect(preview.locator('img')).toHaveAttribute('src', '/assets/electrical-panels-product.png')
    await expect(preview.locator('figcaption')).toHaveText('Current photo.')
    await page.getByLabel('Image', { exact: true }).setInputFiles({ name: 'panel.jpg', mimeType: 'image/jpeg', buffer: readFileSync(join(process.cwd(), 'public/assets/portfolio-solar-array.jpg')) })
    await expect(preview.locator('figcaption')).toHaveText('New photo, as the shop will show it. Save the product to use it.')
    await expect(preview.locator('img')).toHaveAttribute('src', new RegExp(`/api/${UPLOADED_IMAGE}$`))
    expect(api.requests.find((r) => r.path === '/api/admin/product-images')?.body).toEqual({ type: 'image/jpeg', bytes: expect.any(Number) })
    expect(api.requests.some((r) => r.method === 'PATCH')).toBe(false)
    await page.getByRole('button', { name: 'Save changes' }).click()
    await expect(page.locator('.success-message')).toHaveText('Changes saved.')
    expect(api.requests.find((r) => r.method === 'PATCH')?.body).toEqual({ image: UPLOADED_IMAGE })
  })

  test('shows the chosen photo at once and blocks saving while it uploads', async ({ page }) => {
    await mockApi(page)
    let release = () => {}
    const held = new Promise<void>((resolve) => { release = resolve })
    await page.route('**/api/admin/product-images', async (route) => { await held; return route.fallback() })
    await logInAsAdmin(page)
    await page.goto('/#admin/products/panel-001')
    await page.getByLabel('Image', { exact: true }).setInputFiles({ name: 'panel.png', mimeType: 'image/png', buffer: readFileSync(join(process.cwd(), 'public/assets/product-lineup.png')) })
    await expect(page.locator('.admin-image-preview img')).toHaveAttribute('src', /^blob:/)
    await expect(page.locator('.admin-image-preview figcaption')).toHaveText('Uploading your photo…')
    await expect(page.getByRole('button', { name: 'Uploading photo…' })).toBeDisabled()
    release()
    await expect(page.getByRole('button', { name: 'Save changes' })).toBeEnabled()
  })

  test('refuses a HEIC or oversized photo before sending it, and shows a server refusal', async ({ page }) => {
    const api = await mockApi(page, { uploadFails: true })
    await logInAsAdmin(page)
    await page.goto('/#admin/products/panel-001')
    const input = page.getByLabel('Image', { exact: true })
    await input.setInputFiles({ name: 'IMG_0001.HEIC', mimeType: 'image/heic', buffer: Buffer.from('heic') })
    await expect(page.locator('#product-image-upload-error')).toContainText('HEIC format')
    await input.setInputFiles({ name: 'huge.jpg', mimeType: 'image/jpeg', buffer: Buffer.alloc(10 * 1024 * 1024 + 1) })
    await expect(page.locator('#product-image-upload-error')).toHaveText('This photo is 10.0 MB. Choose one under 10 MB.')
    expect(api.requests.some((r) => r.path === '/api/admin/product-images')).toBe(false)
    await input.setInputFiles({ name: 'renamed.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not a photo') })
    await expect(page.locator('#product-image-upload-error')).toHaveText('Choose a JPEG, PNG, or WebP photo. This file could not be read as one.')
    await expect(page.locator('.admin-image-preview img')).toHaveAttribute('src', '/assets/electrical-panels-product.png')
  })

  test('asks for a photo before creating a product', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.goto('/#admin/new')
    await expect(page.locator('.admin-image-preview figcaption')).toHaveText('No photo yet.')
    await page.getByLabel('Product ID').fill('panel-002')
    await page.getByLabel('Name').fill('Second panel')
    await page.getByLabel('Product code').fill('GPEC-CP-002')
    await page.getByLabel('Description', { exact: true }).fill('A sample description.')
    await page.getByLabel('Image description').fill('Photo of a panel')
    await page.getByRole('button', { name: 'Create product' }).click()
    await expect(page.locator('#product-image-error')).toHaveText('Choose a photo for the product.')
    expect(api.requests.some((r) => r.method === 'POST' && r.path === '/api/admin/products')).toBe(false)
  })

  test('without photo storage, a site image path is typed and previewed', async ({ page }) => {
    await mockApi(page, { imageUploads: false })
    await logInAsAdmin(page)
    await page.goto('/#admin/products/panel-001')
    const path = page.getByLabel('Image', { exact: true })
    await expect(path).toHaveValue('/assets/electrical-panels-product.png')
    await expect(page.getByText('Photo uploads are switched on once GPEC’s image storage is set up.')).toBeVisible()
    await path.fill('/assets/product-lineup.png')
    await path.blur()
    await expect(page.locator('.admin-image-preview img')).toHaveAttribute('src', '/assets/product-lineup.png')
    await path.fill('/assets/missing.png')
    await path.blur()
    await expect(page.locator('.admin-image-preview figcaption')).toHaveText('No image found at this address.')
  })

  test('price entry is switched off until the currency is configured', async ({ page }) => {
    await mockApi(page, { currency: null })
    await logInAsAdmin(page)
    await expect(page.getByText('the shop currency has not been configured')).toBeVisible()
    await page.getByRole('link', { name: 'Edit Custom control panel' }).click()
    await expect(page.getByLabel('Price')).toBeDisabled()
  })
})

test.describe('order enquiries and contact requests', () => {
  test('filters enquiries by status, with counts', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('link', { name: 'Order enquiries' }).click()
    await expect(page.locator('.admin-request-list li')).toHaveCount(3)
    await page.getByRole('button', { name: /^New/ }).click()
    await expect(page.locator('.admin-request-list li')).toHaveCount(1)
    await expect(page.getByRole('button', { name: /^New/ })).toHaveAttribute('aria-pressed', 'true')
  })

  test('shows an enquiry with reply links and records a status change', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.goto(`/#admin/enquiries/${ENQUIRY_REF}`)
    await expect(page.getByRole('heading', { name: ENQUIRY_REF })).toBeVisible()
    await expect(page.getByRole('link', { name: 'customer@example.com' })).toHaveAttribute('href', `mailto:customer@example.com?subject=${encodeURIComponent(`Your GPEC request ${ENQUIRY_REF}`)}`)
    await expect(page.getByRole('link', { name: '+234 800 000 0000' })).toHaveAttribute('href', 'tel:+2348000000000')
    await page.getByLabel('Follow-up status').selectOption('in_progress')
    await page.getByRole('button', { name: 'Update status' }).click()
    await expect(page.locator('.success-message')).toHaveText('Status changed to In progress.')
    expect(api.requests.find((r) => r.method === 'PATCH')?.body).toEqual({ status: 'in_progress' })
    await expect(page.locator('.admin-history li').first()).toContainText('New → In progress')
  })

  test('searches enquiries, keeps the status filter, and clears the search', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('link', { name: 'Order enquiries' }).click()
    await expect(page.locator('.admin-request-list li')).toHaveCount(3)
    const search = page.getByRole('searchbox', { name: 'Search' })
    await search.fill('  second customer ')
    await search.press('Enter')
    await expect(page.locator('.admin-request-list li')).toHaveCount(1)
    await expect(page.locator('.admin-request-list li')).toContainText('Second Customer')
    await expect(page.getByRole('button', { name: /^In progress/ })).toContainText('1')
    await page.getByRole('button', { name: /^Closed/ }).click()
    await expect(page.getByText('Nothing matches “second customer”.')).toBeVisible()
    await page.getByRole('button', { name: 'Clear search' }).click()
    await expect(search).toHaveValue('')
    await expect(page.locator('.admin-request-list li')).toHaveCount(1)
    await expect(page.locator('.admin-request-list li')).toContainText('Third Customer')
    await expect(page.getByRole('button', { name: 'Clear search' })).toHaveCount(0)
  })

  test('adds an internal note and shows it first, with the author', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.goto(`/#admin/enquiries/${ENQUIRY_REF}`)
    const notes = page.locator('.admin-note-list li')
    await expect(notes).toHaveCount(1)
    await page.getByLabel('Add a note').fill('Customer accepted the quote.')
    await page.getByRole('button', { name: 'Add note' }).click()
    await expect(page.getByText('Note added.')).toBeFocused()
    expect(api.requests.find((r) => r.method === 'POST' && r.path.endsWith('/notes'))?.body).toEqual({ text: 'Customer accepted the quote.' })
    await expect(notes).toHaveCount(2)
    await expect(notes.first()).toContainText('Customer accepted the quote.')
    await expect(notes.first()).toContainText(`${ADMIN.name} (${ADMIN.email})`)
    await expect(page.getByLabel('Add a note')).toHaveValue('')
  })

  test('keeps the note text when saving fails, and sends nothing when it is empty', async ({ page }) => {
    const api = await mockApi(page, { notesFail: true })
    await logInAsAdmin(page)
    await page.goto(`/#admin/contact-requests/${CONTACT_REF}`)
    await expect(page.getByText('No notes yet.')).toBeVisible()
    await page.getByRole('button', { name: 'Add note' }).click()
    await expect(page.getByText('Write a note before adding it.')).toBeFocused()
    expect(api.requests.some((r) => r.path.endsWith('/notes'))).toBe(false)
    await page.getByLabel('Add a note').fill('Left a voicemail.')
    await page.getByRole('button', { name: 'Add note' }).click()
    await expect(page.locator('.admin-note-form .form-error')).toHaveText('Something went wrong on our side. Please try again.')
    await expect(page.getByLabel('Add a note')).toHaveValue('Left a voicemail.')
  })

  test('shows a contact request message', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    await page.getByRole('link', { name: 'Contact requests' }).click()
    await page.getByRole('link', { name: new RegExp(`Open ${CONTACT_REF}`) }).click()
    await expect(page.locator('.admin-request-message')).toHaveText('Please call me about a solar system.')
  })
})

test.describe('changing your own password', () => {
  test('counts the new password as you type and announces only when it is long enough', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    await page.goto('/#admin/password')
    const newPassword = page.getByLabel('New password', { exact: true })
    const count = page.locator('.admin-password-count')
    const announcement = page.locator('.admin-field [aria-live="polite"]')
    await expect(count).toHaveText('0 of 15 characters')
    await newPassword.fill('fourteen chars')
    await expect(count).toHaveText('14 of 15 characters')
    await expect(announcement).toHaveText('')
    await newPassword.press('!')
    await expect(count).toHaveText('15 characters ✓ long enough')
    await expect(announcement).toHaveText('The new password is long enough.')
    await page.getByLabel('Current password').fill(ADMIN.password)
    await page.getByLabel('New password again').fill('fourteen chars!')
    await page.getByRole('button', { name: 'Change password' }).click()
    await expect(page.locator('.success-message')).toContainText('Your password has been changed.')
    await expect(count).toHaveText('0 of 15 characters')
  })

  test('shows the server refusing a password known from a data breach', async ({ page }) => {
    await mockApi(page)
    await logInAsAdmin(page)
    await page.goto('/#admin/password')
    await page.getByLabel('Current password').fill(ADMIN.password)
    await page.getByLabel('New password', { exact: true }).fill(BREACHED_PASSWORD)
    await page.getByLabel('New password again').fill(BREACHED_PASSWORD)
    await page.getByRole('button', { name: 'Change password' }).click()
    await expect(page.locator('#newPassword-error')).toHaveText('This password has appeared in a data breach, so attackers try it early. Choose a different one.')
    await expect(page.getByLabel('New password', { exact: true })).toHaveAttribute('aria-describedby', 'newPassword-hint newPassword-error')
    await expect(page.locator('#newPassword-hint')).toContainText('Passwords known from data breaches are refused.')
  })

  test('checks length and matching before sending, then reports a wrong current password', async ({ page }) => {
    const api = await mockApi(page)
    await logInAsAdmin(page)
    await page.goto('/#admin/password')
    await page.getByLabel('Current password').fill('wrong current password')
    await page.getByLabel('New password', { exact: true }).fill('too short')
    await page.getByLabel('New password again').fill('too short')
    await page.getByRole('button', { name: 'Change password' }).click()
    await expect(page.locator('#newPassword-error')).toContainText('Use at least 15 characters')
    expect(api.requests.some((r) => r.path === '/api/admin/session/password')).toBe(false)
    await page.getByLabel('New password', { exact: true }).fill('a brand new long passphrase')
    await page.getByLabel('New password again').fill('a brand new long passphrase')
    await page.getByRole('button', { name: 'Change password' }).click()
    await expect(page.locator('#currentPassword-error')).toHaveText('Your current password is incorrect.')
    await page.getByLabel('Current password').fill(ADMIN.password)
    await page.getByRole('button', { name: 'Change password' }).click()
    await expect(page.locator('.success-message')).toContainText('Your password has been changed.')
  })
})
